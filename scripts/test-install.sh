#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work_root="$(mktemp -d "${TMPDIR:-/tmp}/install-selftest.XXXXXX")"
work_root="$(cd "$work_root" && pwd)"
clone="$work_root/original clone @ work"
fixture_home="$work_root/user config"
fixture_bin="$work_root/bin"
config_path="$fixture_home/.config/opencode/opencode.jsonc"
current_marker='Generated by code-agent-harness/scripts/install.sh'
trap 'rm -rf "$work_root"' EXIT

mkdir -p "$clone" "$fixture_home" "$fixture_bin"
if command -v rsync >/dev/null 2>&1; then
  rsync -a --exclude '.git' "$repo_root/" "$clone/"
else
  (cd "$repo_root" && find . -path ./.git -prune -o -print0 | cpio -0pdm --quiet "$clone")
fi

# Stub platform executables so validation cannot make provider or plugin calls.
for harness in claude codex opencode copilot agy; do
  printf '#!/usr/bin/env bash\nprintf '\''[]\\n'\''\n' > "$fixture_bin/$harness"
  chmod +x "$fixture_bin/$harness"
done

run_fixture() {
  env HOME="$fixture_home" PATH="$fixture_bin:$PATH" \
    GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 \
    "$@" > "$work_root/command.log" 2>&1
}

assert() {
  local description="$1"
  shift
  if "$@"; then
    printf 'PASS  %s\n' "$description"
  else
    printf 'FAIL  %s\n' "$description" >&2
    cat "$work_root/command.log" >&2
    exit 1
  fi
}

verification_fails() {
  local exit_status=0
  run_fixture "$clone/scripts/verify.sh" --harness opencode || exit_status=$?
  [ "$exit_status" -eq 1 ] && grep -Fq "missing expected content: $config_path ($1)" "$work_root/command.log"
}

write_config_marker() {
  sed "s|$current_marker|$1|" "$work_root/current.jsonc" > "$config_path"
}

assert 'dry-run succeeds' run_fixture "$clone/scripts/install.sh" --dry-run
assert 'dry-run leaves configuration untouched' test ! -e "$fixture_home/.config"
assert 'installation succeeds from an arbitrary clone name' run_fixture "$clone/scripts/install.sh"
assert 'new config identifies Code Agent Harness' grep -Fq "$current_marker" "$config_path"
assert 'instructions use the absolute clone path' grep -Fq "\"instructions\": [\"$clone/instructions/AGENTS.md\"]" "$config_path"
assert 'skills use the absolute clone path' grep -Fq "\"$clone/skills\"" "$config_path"
assert 'all platforms validate after installation' run_fixture "$clone/scripts/verify.sh" --all
cp "$config_path" "$work_root/current.jsonc"

write_config_marker 'Generated by ai-agent-setup/scripts/install.sh'
assert 'legacy installer marker still validates' run_fixture "$clone/scripts/verify.sh" --harness opencode
assert 'reinstall migrates the legacy config' run_fixture "$clone/scripts/install.sh"
assert 'reinstall writes the new marker' grep -Fq "$current_marker" "$config_path"
assert 'legacy config is backed up' grep -Fq 'Generated by ai-agent-setup/scripts/install.sh' "$config_path".backup-*

write_config_marker 'Generated by unrelated-tool/scripts/install.sh'
assert 'unknown generator marker fails validation' verification_fails 'opencode config generated by install.sh'
sed 's|/instructions/AGENTS.md|/instructions/WRONG.md|' "$work_root/current.jsonc" > "$config_path"
assert 'incorrect instructions path fails validation' verification_fails 'opencode instructions path'
sed 's|/skills"|/wrong-skills"|g' "$work_root/current.jsonc" > "$config_path"
assert 'incorrect skills path fails validation' verification_fails 'opencode skills path'

for marker in "$current_marker" \
  'Generated by ai-agent-setup/scripts/install.sh' \
  'Generated by ai-agent-setup/scripts/link.sh'; do
  write_config_marker "$marker"
  assert "uninstall succeeds for $marker" run_fixture "$clone/scripts/uninstall.sh"
  assert "uninstall removes config for $marker" test ! -e "$config_path"
done

sed '/Generated by /d' "$work_root/current.jsonc" > "$config_path"
cp "$config_path" "$work_root/user.jsonc"
assert 'uninstall succeeds with an unmarked user config' run_fixture "$clone/scripts/uninstall.sh"
assert 'uninstall preserves the unmarked config' cmp -s "$config_path" "$work_root/user.jsonc"

assert 'install restores managed configuration' run_fixture "$clone/scripts/install.sh"
mv "$clone" "$work_root/code-agent-harness @ relocated"
clone="$work_root/code-agent-harness @ relocated"
assert 'relocation requires refreshing absolute paths' verification_fails 'opencode instructions path'
assert 'reinstall succeeds after relocation' run_fixture "$clone/scripts/install.sh"
assert 'relocated instructions use the new clone path' grep -Fq "\"instructions\": [\"$clone/instructions/AGENTS.md\"]" "$config_path"
assert 'relocated skills use the new clone path' grep -Fq "\"$clone/skills\"" "$config_path"
assert 'all platforms validate after relocation' run_fixture "$clone/scripts/verify.sh" --all

printf '\nInstallation self-test passed.\n'
