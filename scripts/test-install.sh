#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work_root="$(mktemp -d "${TMPDIR:-/tmp}/install-selftest.XXXXXX")"
work_root="$(cd "$work_root" && pwd)"
clone="$work_root/original clone @ work"
fixture_home="$work_root/user config"
fixture_bin="$work_root/bin"
config_path="$fixture_home/.config/opencode/opencode.jsonc"
current_marker='Generated by code-agent-harness/scripts/install.sh'
trap 'rm -rf "$work_root"' EXIT

mkdir -p "$clone" "$fixture_home" "$fixture_bin"
if command -v rsync >/dev/null 2>&1; then
  rsync -a --exclude '.git' "$repo_root/" "$clone/"
else
  (cd "$repo_root" && find . -path ./.git -prune -o -print0 | cpio -0pdm --quiet "$clone")
fi

# Stub platform executables so validation cannot make provider or plugin calls.
for harness in claude codex opencode copilot agy; do
  printf '#!/usr/bin/env bash\nprintf '\''[]\\n'\''\n' > "$fixture_bin/$harness"
  chmod +x "$fixture_bin/$harness"
done

run_fixture() {
  env HOME="$fixture_home" PATH="$fixture_bin:$PATH" \
    GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 \
    "$@" > "$work_root/command.log" 2>&1
}

assert() {
  local description="$1"
  shift
  if "$@"; then
    printf 'PASS  %s\n' "$description"
  else
    printf 'FAIL  %s\n' "$description" >&2
    cat "$work_root/command.log" >&2
    exit 1
  fi
}

verification_fails() {
  local exit_status=0
  run_fixture "$clone/scripts/verify.sh" --harness opencode || exit_status=$?
  [ "$exit_status" -eq 1 ] && grep -Fq "missing expected content: $config_path ($1)" "$work_root/command.log"
}

write_config_marker() {
  sed "s|$current_marker|$1|" "$work_root/current.jsonc" > "$config_path"
}

assert 'dry-run succeeds' run_fixture "$clone/scripts/install.sh" --all --dry-run
assert 'dry-run leaves configuration untouched' test ! -e "$fixture_home/.config"
assert 'installation succeeds from an arbitrary clone name' run_fixture "$clone/scripts/install.sh" --all
assert 'new config identifies Code Agent Harness' grep -Fq "$current_marker" "$config_path"
assert 'instructions use the absolute clone path' grep -Fq "\"instructions\": [\"$clone/instructions/AGENTS.md\"]" "$config_path"
assert 'skills use the absolute clone path' grep -Fq "\"$clone/skills\"" "$config_path"
assert 'all platforms validate after installation' run_fixture "$clone/scripts/verify.sh" --all
cp "$config_path" "$work_root/current.jsonc"

write_config_marker 'Generated by ai-agent-setup/scripts/install.sh'
assert 'legacy installer marker still validates' run_fixture "$clone/scripts/verify.sh" --harness opencode
assert 'reinstall migrates the legacy config' run_fixture "$clone/scripts/install.sh" --all
assert 'reinstall writes the new marker' grep -Fq "$current_marker" "$config_path"
assert 'legacy config is backed up' grep -Fq 'Generated by ai-agent-setup/scripts/install.sh' "$config_path".backup-*

write_config_marker 'Generated by unrelated-tool/scripts/install.sh'
assert 'unknown generator marker fails validation' verification_fails 'opencode config generated by install.sh'
sed 's|/instructions/AGENTS.md|/instructions/WRONG.md|' "$work_root/current.jsonc" > "$config_path"
assert 'incorrect instructions path fails validation' verification_fails 'opencode instructions path'
sed 's|/skills"|/wrong-skills"|g' "$work_root/current.jsonc" > "$config_path"
assert 'incorrect skills path fails validation' verification_fails 'opencode skills path'

for marker in "$current_marker" \
  'Generated by ai-agent-setup/scripts/install.sh' \
  'Generated by ai-agent-setup/scripts/link.sh'; do
  write_config_marker "$marker"
  assert "uninstall succeeds for $marker" run_fixture "$clone/scripts/uninstall.sh" --all
  assert "uninstall removes config for $marker" test ! -e "$config_path"
done

sed '/Generated by /d' "$work_root/current.jsonc" > "$config_path"
cp "$config_path" "$work_root/user.jsonc"
assert 'uninstall succeeds with an unmarked user config' run_fixture "$clone/scripts/uninstall.sh" --all
assert 'uninstall preserves the unmarked config' cmp -s "$config_path" "$work_root/user.jsonc"

assert 'install restores managed configuration' run_fixture "$clone/scripts/install.sh" --all
mv "$clone" "$work_root/code-agent-harness @ relocated"
clone="$work_root/code-agent-harness @ relocated"
assert 'relocation requires refreshing absolute paths' verification_fails 'opencode instructions path'
assert 'reinstall succeeds after relocation' run_fixture "$clone/scripts/install.sh" --all
assert 'relocated instructions use the new clone path' grep -Fq "\"instructions\": [\"$clone/instructions/AGENTS.md\"]" "$config_path"
assert 'relocated skills use the new clone path' grep -Fq "\"$clone/skills\"" "$config_path"
assert 'all platforms validate after relocation' run_fixture "$clone/scripts/verify.sh" --all

new_fixture() {
  fixture_home="$work_root/$1"
  config_path="$fixture_home/.config/opencode/opencode.jsonc"
  mkdir -p "$fixture_home"
}

harness_root() {
  case "$1" in
    claude) printf '%s/.claude' "$fixture_home" ;;
    codex) printf '%s/.codex' "$fixture_home" ;;
    opencode) printf '%s/.config/opencode' "$fixture_home" ;;
    copilot) printf '%s/.copilot' "$fixture_home" ;;
    antigravity) printf '%s/.gemini/config' "$fixture_home" ;;
  esac
}

harness_marker() {
  case "$1" in
    opencode) printf '%s/opencode.jsonc' "$(harness_root "$1")" ;;
    copilot) printf '%s/agents' "$(harness_root "$1")" ;;
    *) printf '%s/AGENTS.md' "$(harness_root "$1")" ;;
  esac
}

path_absent() {
  [ ! -e "$1" ] && [ ! -L "$1" ]
}

command_fails_usage() {
  local exit_status=0
  run_fixture "$@" </dev/null || exit_status=$?
  [ "$exit_status" -eq 2 ]
}

log_excludes() {
  ! grep -Fq "$1" "$work_root/command.log"
}

for harness in claude codex opencode copilot antigravity; do
  new_fixture "only $harness"
  assert "$harness installation dry-run succeeds" run_fixture "$clone/scripts/install.sh" --harness "$harness" --dry-run
  assert "$harness dry-run creates no configuration" test -z "$(ls -A "$fixture_home")"
  assert "$harness installation succeeds" run_fixture "$clone/scripts/install.sh" --harness "$harness"
  assert "$harness prints matching verification command" grep -Fq "./scripts/verify.sh --harness $harness" "$work_root/command.log"
  if [ "$harness" != opencode ]; then
    assert "$harness omits the OpenCode restart reminder" log_excludes 'Restart OpenCode'
  fi
  assert "$harness creates shared skills" test -L "$fixture_home/.agents/skills"
  for other_harness in claude codex opencode copilot antigravity; do
    if [ "$other_harness" != "$harness" ]; then
      assert "$harness leaves $other_harness unconfigured" path_absent "$(harness_root "$other_harness")"
    fi
  done
  assert "$harness validates independently" run_fixture "$clone/scripts/verify.sh" --harness "$harness"
  assert "$harness uninstall dry-run succeeds" run_fixture "$clone/scripts/uninstall.sh" --harness "$harness" --dry-run
  assert "$harness remains valid after uninstall dry-run" run_fixture "$clone/scripts/verify.sh" --harness "$harness"
  assert "$harness uninstall succeeds" run_fixture "$clone/scripts/uninstall.sh" --harness "$harness"
  assert "$harness managed config is removed" path_absent "$(harness_marker "$harness")"
  assert "$harness selective uninstall retains shared skills" test -L "$fixture_home/.agents/skills"
done

new_fixture 'multiple tools'
assert 'multiple tools and repeated selections install' run_fixture "$clone/scripts/install.sh" --harness codex --harness opencode --harness codex
assert 'repeated selections are deduplicated' grep -Fxq 'Selected tools: codex opencode' "$work_root/command.log"
assert 'multiple tools validate together' run_fixture "$clone/scripts/verify.sh" --harness codex --harness opencode
assert 'later installation adds another tool' run_fixture "$clone/scripts/install.sh" --harness claude
assert 'later installation leaves earlier tools installed' run_fixture "$clone/scripts/verify.sh" --harness claude --harness codex --harness opencode
assert 'multiple tools uninstall together' run_fixture "$clone/scripts/uninstall.sh" --harness codex --harness opencode --harness codex
assert 'Codex is removed from multiple selection' path_absent "$(harness_marker codex)"
assert 'OpenCode is removed from multiple selection' path_absent "$config_path"
assert 'unselected Claude remains valid' run_fixture "$clone/scripts/verify.sh" --harness claude

new_fixture 'all tools'
assert 'all combines with explicit selections' run_fixture "$clone/scripts/install.sh" --all --harness codex
assert 'all-tools dry-run uninstall succeeds' run_fixture "$clone/scripts/uninstall.sh" --all --dry-run
assert 'all tools remain valid after dry-run uninstall' run_fixture "$clone/scripts/verify.sh" --all
mkdir -p "$fixture_home/.codex/skills/.system" "$fixture_home/.codex/skills/curated"
printf 'keep\n' > "$fixture_home/.codex/skills/.system/keep.txt"
printf 'keep\n' > "$fixture_home/.codex/skills/curated/SKILL.md"
printf 'keep\n' > "$fixture_home/.codex/local-state.txt"
assert 'individually selecting every tool uninstalls' run_fixture "$clone/scripts/uninstall.sh" --harness claude --harness codex --harness opencode --harness copilot --harness antigravity
assert 'individual selection of all five retains shared skills' test -L "$fixture_home/.agents/skills"
assert 'explicit all-tools uninstall succeeds' run_fixture "$clone/scripts/uninstall.sh" --harness codex --all
assert 'explicit all-tools uninstall removes shared skills' path_absent "$fixture_home/.agents/skills"
assert 'Codex system skills are preserved' grep -Fxq keep "$fixture_home/.codex/skills/.system/keep.txt"
assert 'curated skills are preserved' grep -Fxq keep "$fixture_home/.codex/skills/curated/SKILL.md"
assert 'other Codex state is preserved' grep -Fxq keep "$fixture_home/.codex/local-state.txt"

new_fixture 'existing user configuration'
mkdir -p "$fixture_home/.claude" "$fixture_home/.config/opencode" "$fixture_home/.copilot"
printf 'user instructions\n' > "$fixture_home/.claude/AGENTS.md"
printf 'user config\n' > "$config_path"
ln -s "$work_root/user-owned-agents" "$fixture_home/.copilot/agents"
assert 'selective install preserves unselected user config' run_fixture "$clone/scripts/install.sh" --harness claude
assert 'selected user file receives a backup' grep -Fxq 'user instructions' "$fixture_home/.claude/AGENTS.md".backup-*
assert 'unselected OpenCode config is unchanged' grep -Fxq 'user config' "$config_path"
assert 'selective uninstall ignores unselected config' run_fixture "$clone/scripts/uninstall.sh" --harness claude
assert 'unselected foreign symlink is unchanged' test "$(readlink "$fixture_home/.copilot/agents")" = "$work_root/user-owned-agents"
ln -s "$clone-neighbor/instructions/AGENTS.md" "$fixture_home/.claude/AGENTS.md"
assert 'uninstall skips a sibling clone sharing the same path prefix' run_fixture "$clone/scripts/uninstall.sh" --harness claude
assert 'sibling-clone symlink is preserved' test -L "$fixture_home/.claude/AGENTS.md"

for script in install uninstall; do
  new_fixture "$script argument validation"
  if [ "$script" = uninstall ]; then
    assert 'install baseline for uninstall argument checks' run_fixture "$clone/scripts/install.sh" --all
  fi
  assert "$script help succeeds without selection" run_fixture "$clone/scripts/$script.sh" --help
  assert "$script without noninteractive selection fails" command_fails_usage "$clone/scripts/$script.sh"
  assert "$script dry-run still requires selection" command_fails_usage "$clone/scripts/$script.sh" --dry-run
  assert "$script missing harness value fails" command_fails_usage "$clone/scripts/$script.sh" --harness
  assert "$script empty harness value fails" command_fails_usage "$clone/scripts/$script.sh" --harness ''
  assert "$script space-separated harness value fails" command_fails_usage "$clone/scripts/$script.sh" --harness 'claude codex'
  assert "$script invalid harness value fails" command_fails_usage "$clone/scripts/$script.sh" --all --harness unknown
  assert "$script later invalid option fails before changes" command_fails_usage "$clone/scripts/$script.sh" --harness claude --unknown
  if [ "$script" = uninstall ]; then
    assert 'argument errors leave all installed tools valid' run_fixture "$clone/scripts/verify.sh" --all
  else
    assert 'argument errors and help create no configuration' test -z "$(ls -A "$fixture_home")"
  fi
done

assert 'terminal menus pass integration checks' run_fixture python3 "$repo_root/scripts/test-harness-menu.py" "$clone" "$work_root"

printf '\nInstallation self-test passed.\n'
